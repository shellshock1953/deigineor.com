#!/usr/bin/env node
/**
 * build-logo.mjs
 *
 * Downloads the Unbounded (weight 900) font, lays out "DEIGINEOR" with
 * generous tracking, and generates real glyph outline paths for:
 * 1. src/components/logo-paths.ts (TypeScript constants for Logo.tsx and opengraph-image.tsx)
 * 2. public/logo.svg (standalone full wordmark SVG)
 * 3. public/favicon.svg (standalone compact 'D + wave' favicon SVG)
 *
 * Usage:
 *   cd v2/app && node scripts/build-logo.mjs
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import opentype from 'opentype.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const appDir = path.resolve(__dirname, '..')

// Source font: Unbounded Black (900) from @fontsource/unbounded or Google Fonts repo
const FONT_URL =
  'https://cdn.jsdelivr.net/npm/@fontsource/unbounded/files/unbounded-latin-900-normal.woff'

console.log('Fetching Unbounded font from:', FONT_URL)
const response = await fetch(FONT_URL)
if (!response.ok) {
  throw new Error(`Failed to fetch font: ${response.status} ${response.statusText}`)
}
const fontBuffer = await response.arrayBuffer()
const font = opentype.parse(fontBuffer)
console.log('Font loaded successfully.')

// --- WORDMARK GEOMETRY ---
const WORDMARK_VIEWBOX = '0 0 1152 260'
const text = 'DEIGINEOR'
const fontSize = 135
const baseline = 175 // Cap-height is ~102, so letters span y: 73..175 (midpoint: 124)
const tracking = 14 // Extra spacing between glyphs

// Measure advances and layout
const glyphs = []
let totalWidth = 0
for (let i = 0; i < text.length; i++) {
  const char = text[i]
  const glyph = font.charToGlyph(char)
  const adv = glyph.advanceWidth * (fontSize / font.unitsPerEm)
  glyphs.push({ char, glyph, adv })
  totalWidth += adv
  if (i < text.length - 1) totalWidth += tracking
}

const startX = Math.round((1152 - totalWidth) / 2)
let curX = startX
const letters = []

for (let i = 0; i < glyphs.length; i++) {
  const { char, glyph, adv } = glyphs[i]
  const p = glyph.getPath(curX, baseline, fontSize)
  letters.push({
    char,
    x: curX,
    d: p.toPathData(2),
  })
  curX += adv + tracking
}

const wordmarkCombinedPath = letters.map((l) => l.d).join(' ')

// Cut band: 12px gap centered at y=124 (top: 118, bottom: 130)
const WORDMARK_CUT_GAP = { top: 118, bottom: 130 }

// Waveform: ONE continuous line, organic noise on left half -> clean sine on right half
// Midpoint y = 124, max amplitude 4.5 to fit cleanly in the 12px cut band.
function generateWordmarkWave(width = 1152, midY = 124, maxAmp = 4.5) {
  const points = []
  const step = 6

  for (let x = 0; x <= width; x += step) {
    let y = midY
    if (x < 580) {
      // Left half: organic oscilloscope noise (multi-frequency harmonics + gentle jitter)
      const t = x / 60
      const noise =
        Math.sin(t * 1.7) * 2.4 +
        Math.sin(t * 3.1) * 1.6 +
        Math.cos(t * 0.8) * 1.2
      const transient = Math.sin(x * 0.2) > 0.88 ? Math.sin(x * 0.5) * 1.8 : 0
      y = midY + Math.max(-maxAmp, Math.min(maxAmp, noise + transient))
    } else if (x <= 660) {
      // Smooth transition zone
      const blend = (x - 580) / 80
      const t = x / 60
      const organic = Math.sin(t * 1.7) * 2.4 + Math.sin(t * 3.1) * 1.6
      const sine = Math.sin(((x - 660) / 56) * Math.PI * 2) * maxAmp
      const mixed = organic * (1 - blend) + sine * blend
      y = midY + Math.max(-maxAmp, Math.min(maxAmp, mixed))
    } else {
      // Right half: clean decaying sine wave
      const wavelength = 56
      const amp = maxAmp - ((x - 660) / (width - 660)) * 1.0 // 4.5 down to 3.5
      y = midY + Math.sin(((x - 660) / wavelength) * Math.PI * 2) * amp
    }
    points.push({ x, y })
  }

  // Smooth quadratic Bezier curve
  let d = `M${points[0].x},${points[0].y.toFixed(2)}`
  for (let i = 1; i < points.length; i++) {
    const prev = points[i - 1]
    const curr = points[i]
    const mx = (prev.x + curr.x) / 2
    const my = (prev.y + curr.y) / 2
    d += ` Q${prev.x.toFixed(2)},${prev.y.toFixed(2)} ${mx.toFixed(2)},${my.toFixed(2)}`
  }
  const last = points[points.length - 1]
  d += ` L${last.x},${last.y.toFixed(2)}`
  return d
}

const WORDMARK_WAVE = generateWordmarkWave(1152, 124, 4.5)

// --- COMPACT MARK GEOMETRY (64x64) ---
const MARK_VIEWBOX = '0 0 64 64'
const markFontSize = 44
const markBaseline = 48.5
const glyphD = font.charToGlyph('D')
const markDPath = glyphD.getPath(13.25, markBaseline, markFontSize).toPathData(2)
const MARK_CUT_GAP = { top: 30, bottom: 34 }

// Short organic-to-sine wave for 64x64
const MARK_WAVE =
  'M2,32 C6,31.2 9,33.5 13,32.2 C17,30.8 21,33.2 25,31.8 C29,30.5 33,33.5 38,32 C43,30.5 48,33.5 54,32 C58,31 61,32.5 62,32'

// --- WRITE src/components/logo-paths.ts ---
const logoPathsTs = `// Generated by scripts/build-logo.mjs — do not edit directly.
// To regenerate: cd v2/app && node scripts/build-logo.mjs

export const WORDMARK_VIEWBOX = '${WORDMARK_VIEWBOX}'

export const WORDMARK_CUT_GAP = {
  top: ${WORDMARK_CUT_GAP.top},
  bottom: ${WORDMARK_CUT_GAP.bottom},
} as const

export const WORDMARK_WAVE =
  '${WORDMARK_WAVE}'

export const WORDMARK_PATH =
  '${wordmarkCombinedPath}'

export const LETTERS: string[] = [
${letters.map((l) => `  // ${l.char}\n  '${l.d}',`).join('\n')}
]

export const MARK_VIEWBOX = '${MARK_VIEWBOX}'

export const MARK_CUT_GAP = {
  top: ${MARK_CUT_GAP.top},
  bottom: ${MARK_CUT_GAP.bottom},
} as const

export const MARK_WAVE =
  '${MARK_WAVE}'

export const MARK_D_PATH =
  '${markDPath}'
`

fs.writeFileSync(path.join(appDir, 'src/components/logo-paths.ts'), logoPathsTs)
console.log('Wrote src/components/logo-paths.ts')

// --- WRITE public/logo.svg ---
const logoSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${WORDMARK_VIEWBOX}" role="img" aria-label="DEIGINEOR">
  <defs>
    <clipPath id="cut">
      <rect x="0" y="0" width="1152" height="${WORDMARK_CUT_GAP.top}"/>
      <rect x="0" y="${WORDMARK_CUT_GAP.bottom}" width="1152" height="${260 - WORDMARK_CUT_GAP.bottom}"/>
    </clipPath>
  </defs>
  <path d="${wordmarkCombinedPath}" fill="#e8e2d4" fill-rule="evenodd" clip-path="url(#cut)"/>
  <path d="${WORDMARK_WAVE}" fill="none" stroke="#9cff6b" stroke-width="2.5" stroke-linecap="round" vector-effect="non-scaling-stroke"/>
</svg>
`

fs.writeFileSync(path.join(appDir, 'public/logo.svg'), logoSvg)
console.log('Wrote public/logo.svg')

// --- WRITE public/favicon.svg ---
const faviconSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${MARK_VIEWBOX}">
  <rect width="64" height="64" rx="14" fill="#0d1210"/>
  <defs>
    <clipPath id="mcut">
      <rect x="0" y="0" width="64" height="${MARK_CUT_GAP.top}"/>
      <rect x="0" y="${MARK_CUT_GAP.bottom}" width="64" height="${64 - MARK_CUT_GAP.bottom}"/>
    </clipPath>
  </defs>
  <path d="${markDPath}" fill="#e8e2d4" fill-rule="evenodd" clip-path="url(#mcut)"/>
  <path d="${MARK_WAVE}" fill="none" stroke="#9cff6b" stroke-width="1.8" stroke-linecap="round"/>
</svg>
`

fs.writeFileSync(path.join(appDir, 'public/favicon.svg'), faviconSvg)
console.log('Wrote public/favicon.svg')

console.log('Logo build complete!')
